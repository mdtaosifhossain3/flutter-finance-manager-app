/// Keyword data for [TransactionParser]. Only data lives here, so teaching the
/// parser a new word means adding it to a list below.
///
/// Words are matched on whole tokens, also with common Bangla/Banglish endings
/// ("বিকাশে", "bazare", "rickshay"), so list the base form only.
/// Multi-word entries ("bari vara") are matched as phrases and beat single
/// words. Spelling variants of Banglish words of 5+ letters are tolerated.
library;

class KeywordGroup {
  final String category;
  final String title;
  final List<String> words;

  /// 1 = generic word ("bill", "vara"), 2 = normal. A more specific word
  /// in the same sentence wins over a generic one.
  final int weight;

  const KeywordGroup(this.category, this.title, this.words, {this.weight = 2});
}

